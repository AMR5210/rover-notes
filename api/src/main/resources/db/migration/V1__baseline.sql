-- Rover Notes 2.0 — baseline schema
--
-- One Postgres serving vector search, lexical search, a bounded entity graph,
-- a job queue, and cost accounting. See `docs/ARCHITECTURE.md`
--
-- Embedding dimension 384 matches BAAI/bge-small-en-v1.5 (see docs/ARCHITECTURE.md).
-- Changing the embedding model means a new column and a backfill, not an ALTER.

create extension if not exists vector;
create extension if not exists pg_trgm;
create extension if not exists pgcrypto;

-- ============================================================ documents

create table documents (
    id            uuid primary key default gen_random_uuid(),
    owner_id      uuid        not null,
    title         text        not null,
    source_type   text        not null default 'note',   -- note | pdf | web | email | code
    source_uri    text,                                  -- s3 key, URL, or null for notes
    content       text,                                  -- extracted plain text
    content_hash  text        not null,                  -- sha256; drives re-index idempotency
    metadata      jsonb       not null default '{}'::jsonb,
    created_at    timestamptz not null default now(),
    updated_at    timestamptz not null default now(),

    constraint documents_source_type_check
        check (source_type in ('note', 'pdf', 'web', 'email', 'code', 'audio', 'image'))
);

create index documents_owner_updated_idx on documents (owner_id, updated_at desc);

-- Known-item lookup: "find the file about X" resolves here in single-digit ms
-- before any neural work happens. See docs/ARCHITECTURE.md, routing stage.
create index documents_title_trgm_idx on documents using gin (title gin_trgm_ops);

create index documents_metadata_idx on documents using gin (metadata jsonb_path_ops);

-- ============================================================ chunks

create table chunks (
    id                     uuid  primary key default gen_random_uuid(),
    document_id            uuid  not null references documents (id) on delete cascade,

    -- Denormalised from documents so owner filters push down into the same
    -- index scan as the vector search rather than forcing a join first.
    owner_id               uuid  not null,

    ordinal                int   not null,
    content                text  not null,

    -- Contextual retrieval: `content` prefixed with a chunk-situating sentence
    -- generated by a cheap model. This is what gets embedded; `content` is what
    -- gets shown to the user. Populated in Week 4.
    contextualized_content text,

    -- sha256 of `content`. Ingestion skips re-embedding when unchanged, so
    -- editing one paragraph of a 40-page document re-embeds one chunk, not 400.
    content_hash           text  not null,

    token_count            int,

    -- Character offsets into documents.content, for span-level citation grounding.
    char_start             int,
    char_end               int,

    embedding              vector(384),

    tsv tsvector generated always as (to_tsvector('english', content)) stored,

    created_at             timestamptz not null default now(),

    constraint chunks_ordinal_unique unique (document_id, ordinal)
);

-- Dense channel. m/ef_construction are starting values; ef_search is tuned at
-- query time against the eval set in Week 4, not guessed.
create index chunks_embedding_hnsw_idx
    on chunks using hnsw (embedding vector_cosine_ops)
    with (m = 16, ef_construction = 64);

-- Lexical channel. Carries known-item queries, where dense retrieval is weakest.
create index chunks_tsv_idx on chunks using gin (tsv);

create index chunks_owner_idx    on chunks (owner_id);
create index chunks_document_idx on chunks (document_id);
create index chunks_hash_idx     on chunks (content_hash);

-- ============================================================ entity graph
--
-- Relational, not a graph database: traversal is bounded at 2 hops from a
-- retrieved seed set, which is two joins. See docs/ARCHITECTURE.md.

create table entities (
    id           uuid primary key default gen_random_uuid(),
    owner_id     uuid not null,
    name         text not null,
    entity_type  text not null,          -- person | project | concept | org | ...
    canonical_id uuid references entities (id) on delete set null,  -- alias resolution
    created_at   timestamptz not null default now(),

    constraint entities_name_unique unique (owner_id, name, entity_type)
);

create index entities_owner_idx     on entities (owner_id);
create index entities_name_trgm_idx on entities using gin (name gin_trgm_ops);

create table entity_mentions (
    entity_id  uuid not null references entities (id) on delete cascade,
    chunk_id   uuid not null references chunks (id)   on delete cascade,
    confidence real not null default 1.0,

    primary key (entity_id, chunk_id)
);

create index entity_mentions_chunk_idx on entity_mentions (chunk_id);

create table entity_edges (
    src_id      uuid not null references entities (id) on delete cascade,
    dst_id      uuid not null references entities (id) on delete cascade,
    relation    text not null,
    confidence  real not null default 1.0,
    source_doc  uuid references documents (id) on delete set null,
    created_at  timestamptz not null default now(),

    primary key (src_id, dst_id, relation)
);

create index entity_edges_dst_idx on entity_edges (dst_id);

-- ============================================================ outbox
--
-- Transactional outbox + job queue. Written in the same transaction as the
-- document, so there is no dual-write problem. See docs/ARCHITECTURE.md.

create table outbox (
    id              bigserial   primary key,
    aggregate_type  text        not null,      -- document | chunk
    aggregate_id    uuid        not null,
    event_type      text        not null,      -- document.created | document.updated | ...
    payload         jsonb       not null default '{}'::jsonb,
    status          text        not null default 'pending',
    attempts        int         not null default 0,
    last_error      text,
    next_attempt_at timestamptz not null default now(),
    created_at      timestamptz not null default now(),
    updated_at      timestamptz not null default now(),

    constraint outbox_status_check
        check (status in ('pending', 'processing', 'done', 'failed'))
);

-- Partial index: workers only ever scan claimable rows, so the index stays
-- small regardless of how much completed history accumulates.
create index outbox_claim_idx
    on outbox (next_attempt_at, id)
    where status = 'pending';

create index outbox_status_idx on outbox (status);

