-- ============================================================ model registry
--
-- Models are rows, not an enum: adding one is a migration, not a deploy.
-- Capability flags gate the UI — a model without tool support cannot be
-- selected for agent mode.

create table models (
    id                 text primary key,          -- 'anthropic/claude-sonnet-5'
    provider           text not null,             -- anthropic | openai_compat | ollama
    model_id           text not null,             -- provider-native identifier
    display_name       text not null,
    tier               text not null,             -- budget | balanced | frontier
    cost_in_per_mtok   numeric(10, 4),
    cost_out_per_mtok  numeric(10, 4),
    context_window     int  not null,
    supports_tools     boolean not null default false,
    supports_streaming boolean not null default true,
    enabled            boolean not null default true,
    created_at         timestamptz not null default now(),

    constraint models_provider_check check (provider in ('anthropic', 'openai_compat', 'ollama')),
    constraint models_tier_check     check (tier in ('budget', 'balanced', 'frontier'))
);

