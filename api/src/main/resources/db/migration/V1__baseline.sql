-- ============================================================ usage + cost
--
-- Per-request cost attribution. Cache reads are tracked separately because they
-- bill at ~0.1x — folding them into input_tokens would overstate spend by ~10x
-- on the contextual-retrieval path.

create table llm_usage (
    id                bigserial   primary key,
    owner_id          uuid,
    request_id        text,
    model_id          text        not null references models (id),
    task              text        not null,  -- synthesis | classify | contextualize | judge | agent
    input_tokens      int         not null default 0,
    output_tokens     int         not null default 0,
    cache_read_tokens int         not null default 0,
    cache_write_tokens int        not null default 0,
    cost_usd          numeric(12, 6),
    latency_ms        int,
    ttft_ms           int,
    created_at        timestamptz not null default now()
);

create index llm_usage_owner_time_idx on llm_usage (owner_id, created_at desc);

-- BRIN rather than B-tree: this table is append-only and physically ordered by
-- time, which is exactly the access pattern BRIN is built for — at a fraction of
-- the index size. This is also why TimescaleDB is not here (docs/ARCHITECTURE.md).
create index llm_usage_time_brin_idx on llm_usage using brin (created_at);

-- ============================================================ user settings

create table user_settings (
    owner_id             uuid primary key,
    default_model_id     text references models (id),
    monthly_budget_usd   numeric(10, 2),
    created_at           timestamptz not null default now(),
    updated_at           timestamptz not null default now()
);

-- ============================================================ event publication
--
-- Spring Modulith's JDBC event publication registry — the durable outbox described
-- in docs/ARCHITECTURE.md. Modulith can create this table itself, but that initializer and
-- Flyway both run at startup with no ordering between them: whichever creates a
-- table first leaves the schema non-empty for the other. Owning the DDL here makes
-- the migration the single source of truth, so `modulith.events.jdbc
-- .schema-initialization.enabled` is set to false.
--
-- This is the v2 schema shipped with Spring Modulith 2.1.0
-- (org/springframework/modulith/events/jdbc/schemas/v2/schema-postgresql.sql).
-- A Modulith upgrade that changes the schema version needs a matching migration.

create table event_publication (
    id                     uuid        not null primary key,
    listener_id            text        not null,
    event_type             text        not null,
    serialized_event       text        not null,
    publication_date       timestamptz not null,
    completion_date        timestamptz,
    status                 text,
    completion_attempts    int,
    last_resubmission_date timestamptz
);

-- Resubmission looks events up by payload, and the hash index is roughly half the
-- size of a B-tree for equality-only lookups on text this wide.
create index event_publication_serialized_event_hash_idx
    on event_publication using hash (serialized_event);

-- Incomplete publications are the ones the registry replays on restart.
create index event_publication_by_completion_date_idx
    on event_publication (completion_date);
